#!/usr/bin/env python3
"""Writes the public API of SfereAnalytics as text, from the compiler's symbol graphs.

    python3 -I tools/api_dump.py <symbol-graph-dir> > api/SfereAnalytics.api

The symbol graph directory is what `-emit-symbol-graph -emit-symbol-graph-dir <dir>` writes
while compiling the module (tools/api_dump.sh does that for the iOS Simulator). Only
`SfereAnalytics.symbols.json` and its extension files (`SfereAnalytics@<Module>.symbols.json`)
are read; the base library's graphs in the same directory are ignored.

One line per public or open declaration, plus one line per protocol conformance and
superclass, sorted, so the file diffs cleanly: a change to what `import SfereAnalytics`
exposes shows up as a change to this file. Synthesized members (default implementations
a type inherits from a protocol) are left out; they change with the standard library,
not with this SDK. The same idea as the Android SDK's `sfere-analytics.api`.
"""

import glob
import json
import os
import sys

MODULE = "SfereAnalytics"
PUBLIC = {"public", "open"}
RELATIONS = {"conformsTo": ":", "inheritsFrom": "<"}


def fragments(symbol):
    text = "".join(f["spelling"] for f in symbol.get("declarationFragments", []))
    return " ".join(text.split())


def main(directory):
    files = sorted(
        glob.glob(os.path.join(directory, f"{MODULE}.symbols.json"))
        + glob.glob(os.path.join(directory, f"{MODULE}@*.symbols.json"))
    )
    if not files:
        sys.exit(f"api_dump: no {MODULE} symbol graph in {directory}")
    lines = set()
    for path in files:
        with open(path, encoding="utf-8") as handle:
            graph = json.load(handle)
        extended = os.path.basename(path)[len(MODULE) + 1 : -len(".symbols.json")]
        prefix = f"[extension {extended}] " if extended else ""
        names = {}
        for symbol in graph.get("symbols", []):
            precise = symbol["identifier"]["precise"]
            if symbol.get("accessLevel") not in PUBLIC or "::SYNTHESIZED::" in precise:
                continue
            name = ".".join(symbol["pathComponents"])
            names[precise] = name
            lines.add(f"{prefix}{name} | {fragments(symbol)}")
        for relation in graph.get("relationships", []):
            arrow = RELATIONS.get(relation["kind"])
            source = names.get(relation["source"])
            if arrow and source:
                target = relation.get("targetFallback") or relation["target"]
                lines.add(f"{prefix}{source} {arrow} {target}")
    print(f"// Public API of {MODULE} (iOS). Generated by tools/api_dump.sh: do not edit by hand.")
    for line in sorted(lines):
        print(line)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
